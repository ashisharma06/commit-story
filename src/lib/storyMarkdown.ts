import { asciiBar, formatCount } from "@/lib/stats";

export type StoryMarkdownData = {
  owner: string;
  repo: string;
  siteUrl: string;
  title: string;
  description: string;
  totalCommits: number;
  totalContributors: number;
  totalPullRequests: number;
  yearsActive: string;
  topLanguage: string;
  firstCommitAt: string | null;
  lastCommitAt: string | null;
  languages: readonly { name: string; share: number }[];
};

function dateLine(label: string, value: string | null): string | null {
  if (!value) return null;
  return `${label}: ${value.slice(0, 10)}`;
}

/** Builds the downloadable story, entirely from data already rendered on the page. */
export function storyMarkdown(
  data: StoryMarkdownData,
  narrative: string,
): string {
  const meta = [
    `commits: ${formatCount(data.totalCommits)}`,
    `contributors: ${formatCount(data.totalContributors)}`,
    `pull requests: ${formatCount(data.totalPullRequests)}`,
    `years active: ${data.yearsActive}`,
    `top language: ${data.topLanguage}`,
    dateLine("first commit", data.firstCommitAt),
    dateLine("last commit", data.lastCommitAt),
  ].filter((line): line is string => line !== null);

  const languages =
    data.languages.length > 0
      ? data.languages
          .slice(0, 8)
          .map(
            (language) =>
              `- ${language.name}: ${Math.round(language.share * 100)}% ${asciiBar(language.share)}`,
          )
      : ["- no language data reported"];

  return [
    `# ${data.title}`,
    "",
    `> ${data.description}`,
    "",
    "```text",
    ...meta,
    "```",
    "",
    "## Languages",
    "",
    ...languages,
    "",
    "## Narrative",
    "",
    narrative.trim() || "_No narrative available._",
    "",
    "---",
    `generated by commit story · ${data.siteUrl}/story/${data.owner}/${data.repo}`,
    "",
  ].join("\n");
}
